#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MatchedContent {
    AnyBytes,
    NormalisedText,
}

impl MatchedContent {
    const fn byte_costs(self) -> &'static [u8; 256] {
        match self {
            Self::AnyBytes => &ANY_BYTES_COST_SIXTEENTHS_OF_A_BIT,
            Self::NormalisedText => &NORMALISED_TEXT_COST_SIXTEENTHS_OF_A_BIT,
        }
    }
}

const SIXTEENTHS_PER_BIT: u32 = 16;

#[must_use]
pub fn rarity_of(window: &[u8], content: MatchedContent) -> u32 {
    let costs = content.byte_costs();
    let total: u32 = window
        .iter()
        .map(|byte| u32::from(costs.get(usize::from(*byte)).copied().unwrap_or(0)))
        .sum();
    let repeats_one_byte = window
        .split_first()
        .is_some_and(|(first, rest)| rest.iter().all(|byte| byte == first));
    if repeats_one_byte { total / 4 } else { total }
}

#[must_use]
pub fn spread_penalty(possible_displacements: u32) -> u32 {
    SIXTEENTHS_PER_BIT
        .saturating_mul(u32::BITS.saturating_sub(possible_displacements.leading_zeros()))
}

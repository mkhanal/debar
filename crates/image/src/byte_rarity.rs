const SIXTEENTHS_PER_BIT: u32 = 16;

#[must_use]
pub fn rarity_of(window: &[u8]) -> u32 {
    let total: u32 = window
        .iter()
        .map(|byte| {
            u32::from(
                BYTE_COST_SIXTEENTHS_OF_A_BIT
                    .get(usize::from(*byte))
                    .copied()
                    .unwrap_or(0),
            )
        })
        .sum();
    let repeats_one_byte = window
        .split_first()
        .is_some_and(|(first, rest)| rest.iter().all(|byte| byte == first));
    if repeats_one_byte { total / 4 } else { total }
}

#[must_use]
pub fn spread_penalty(possible_displacements: u32) -> u32 {
    SIXTEENTHS_PER_BIT
        .saturating_mul(u32::BITS.saturating_sub(possible_displacements.leading_zeros()))
}

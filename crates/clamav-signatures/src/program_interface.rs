#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InterfaceTypeKind {
    Function,
    Struct,
    Array,
    Pointer,
}

pub struct InterfaceType {
    pub kind: InterfaceTypeKind,
    pub elements: u32,
    pub contained: &'static [u16],
}

pub const FIRST_DEFINED_TYPE: u16 = 69;
const I8: u16 = 8;
const I16: u16 = 16;
const I32: u16 = 32;
const I64: u16 = 64;
const P8: u16 = 65;

const fn interface(
    kind: InterfaceTypeKind,
    elements: u32,
    contained: &'static [u16],
) -> InterfaceType {
    InterfaceType {
        kind,
        elements,
        contained,
    }
}

const fn defined(index: u16) -> u16 {
    FIRST_DEFINED_TYPE.saturating_add(index)
}

